#!/usr/bin/env node
/**
 * Generate the MCP tool catalog from the code that registers the tools.
 *
 *   node scripts/generate-tool-catalog.mjs           # write it
 *   node scripts/generate-tool-catalog.mjs --check   # fail if stale
 *
 * WHY. `docs/systems/mcp-server.md` carried a hand-written catalog. Measured
 * 2026-08-30: 114 tools exist, 12 were undocumented, and 6 documented tools had been
 * deleted — `cleanup_dalive_sites`, `evaluate_prompt`, `manage_github_repos`,
 * `migrate_storefront_names`, `github_change_account` among them. Wrong in both
 * directions, which is what a hand-maintained list of enumerable things always
 * becomes here: the ADR table stopped four rows short, the backlog index hid three
 * items for months, and two convention counts were wrong within an hour.
 *
 * An agent reads this catalog to decide what it can do. A phantom tool sends it
 * looking for a capability that does not exist; a missing one hides a capability it
 * has. Both are worse than no catalog.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'fs';
import { join } from 'path';

const ROOT = process.cwd();
const OUT = 'docs/systems/mcp-tools.md';

const SOURCES = [
    ...readdirSync(join(ROOT, 'src/features/ai/server'))
        .filter((f) => f.endsWith('.ts'))
        .map((f) => `src/features/ai/server/${f}`),
    'src/mcp-server.ts',
].filter((f) => existsSync(join(ROOT, f)));

/** A tool is either a descriptor row or a direct `registerTool` call. */
function collect() {
    const tools = new Map();

    for (const file of SOURCES) {
        const src = readFileSync(join(ROOT, file), 'utf8');

        // Find every tool NAME first, then read a window after it for the metadata.
        // The first version matched whole object literals and captured 30 of 114,
        // because the shapes differ between descriptor files and registrars — a
        // generator that silently covers a quarter is worse than the list it replaces.
        const seen = [];
        for (const m of src.matchAll(/tool:\s*'([a-z_]+)'/g)) {
            seen.push({ name: m[1], at: m.index, kind: 'descriptor' });
        }
        for (const m of src.matchAll(/registerTool\(\s*'([a-z_]+)'/g)) {
            seen.push({ name: m[1], at: m.index, kind: 'registrar' });
        }

        for (const { name, at, kind } of seen) {
            if (tools.has(name)) continue;
            const window = src.slice(at, at + 600);
            const desc =
                window.match(/description:\s*\n?\s*'([^']{5,200})/) ??
                window.match(/description:\s*\n?\s*"([^"]{5,200})/) ??
                window.match(/description:\s*\n?\s*`([^`]{5,200})/) ??
                window.match(/title:\s*'([^']{5,120})'/);
            tools.set(name, {
                name,
                file,
                kind,
                readOnly: /readOnly:\s*true/.test(window),
                confirm: /confirm:\s*true/.test(window),
                description: desc ? desc[1] : '',
            });
        }
    }
    return [...tools.values()].sort((a, b) => a.name.localeCompare(b.name));
}

const tools = collect();
const byFile = new Map();
for (const t of tools) {
    if (!byFile.has(t.file)) byFile.set(t.file, []);
    byFile.get(t.file).push(t);
}

function render() {
    const L = [];
    L.push('# MCP tool catalog');
    L.push('');
    L.push('**Generated by `npm run docs:tools` — do not hand-edit.**');
    L.push('');
    L.push(`${tools.length} tools, grouped by the module that registers them.`);
    L.push('');
    L.push('`confirm` marks a tool that refuses to act without `confirm: true` — the');
    L.push('destructive ones. A refusal answers PROSE, not JSON, so an agent parsing every');
    L.push('response as JSON will fail on one.');
    L.push('');
    L.push('How a tool is written, and what disqualifies a handler from becoming one, is in');
    L.push('[mcp-tool-authoring](../../.claude/skills/mcp-tool-authoring/SKILL.md). What the');
    L.push('server IS — transport, lifecycle, scoping, security — is in');
    L.push('[mcp-server.md](mcp-server.md).');
    L.push('');
    for (const [file, group] of [...byFile].sort()) {
        L.push(`## \`${file}\``);
        L.push('');
        L.push('| Tool | | What it does |');
        L.push('|---|---|---|');
        for (const t of group) {
            const flag = t.confirm ? '**confirm**' : t.readOnly ? 'read' : '';
            const desc = t.description.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
            L.push(`| \`${t.name}\` | ${flag} | ${desc} |`);
        }
        L.push('');
    }
    return L.join('\n');
}

const body = render();

if (process.argv.includes('--check')) {
    const existing = existsSync(join(ROOT, OUT)) ? readFileSync(join(ROOT, OUT), 'utf8') : '';
    if (existing !== body) {
        console.error(`${OUT} is out of date — run \`npm run docs:tools\``);
        process.exit(1);
    }
    console.log(`Tool catalog current: ${tools.length} tools.`);
    process.exit(0);
}

writeFileSync(join(ROOT, OUT), body);
console.log(`Wrote ${OUT} — ${tools.length} tools across ${byFile.size} modules.`);
console.log(`  ${tools.filter((t) => t.confirm).length} require confirm`);
console.log(`  ${tools.filter((t) => !t.description).length} have no description in the source`);
