#!/usr/bin/env node
/**
 * Work out the one Node Demo Builder runs on, from what each shipped component declares
 * (PR-1a). Nobody types the number: this reads every source `listNodeSources()` names
 * (each GitHub repo at the ref Demo Builder installs, each npm package it installs),
 * applies `chooseNode()`'s rule, and writes the answer with its evidence to
 * `src/core/shell/config/node-version.generated.json`.
 *
 *   npm run node:resolve             write the file
 *   npm run node:resolve -- --check  compare only; exit 1 on any difference
 *
 * Fails, writing nothing, when the ranges do not overlap (naming the ones that block)
 * or a source cannot be read. The rule and the source list live in typechecked,
 * tested code (`src/features/components/services/nodeResolution.ts`); this file only
 * fetches and writes, so it bundles that module with esbuild rather than copying it.
 * A generator, like `docs:tools`, not a check: it reads the network, so it runs at a
 * release cut (`cut-release`), never in the gate.
 */

import { build } from 'esbuild';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';
import { pathToFileURL } from 'url';
import semver from 'semver';

const OUT = 'src/core/shell/config/node-version.generated.json';
const CHECK = process.argv.includes('--check');

async function loadResolution() {
    const dir = mkdtempSync(join(tmpdir(), 'node-resolve-'));
    const file = join(dir, 'nodeResolution.mjs');
    try {
        await build({
            entryPoints: ['src/features/components/services/nodeResolution.ts'],
            bundle: true,
            platform: 'node',
            format: 'esm',
            outfile: file,
            tsconfig: 'tsconfig.json',
            logLevel: 'error',
        });
        return await import(pathToFileURL(file).href);
    } finally {
        rmSync(dir, { recursive: true, force: true });
    }
}

async function getText(url) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    return res.text();
}

/** `name@version` split at the LAST @, so a scoped package keeps its own. */
function splitRef(ref) {
    const at = ref.lastIndexOf('@');
    return [ref.slice(0, at), ref.slice(at + 1)];
}

/** The Node range one source declares, or undefined when it declares none. */
async function rangeOf(source, engineRangeOf) {
    const [name, at] = splitRef(source.ref);
    if (source.from === 'github') {
        return engineRangeOf(await getText(`https://raw.githubusercontent.com/${name}/${at}/package.json`));
    }
    const doc = JSON.parse(await getText(`https://registry.npmjs.org/${name.replace('/', '%2F')}`));
    const version = at === 'latest' ? doc['dist-tags'].latest : semver.maxSatisfying(Object.keys(doc.versions), at);
    if (!version) throw new Error(`${source.ref}: no published version matches`);
    const range = doc.versions[version].engines?.node;
    return typeof range === 'string' && range.trim() ? range : undefined;
}

function sameAnswer(a, b) {
    const keep = (x) => JSON.stringify({ node: x.node, sources: x.sources, excluded: x.excluded });
    return keep(a) === keep(b);
}

function readCurrent() {
    try {
        return JSON.parse(readFileSync(OUT, 'utf8'));
    } catch {
        return {};
    }
}

async function main() {
    const { listNodeSources, excludedNodeSources, chooseNode, engineRangeOf } = await loadResolution();
    const sources = [];
    for (const source of await listNodeSources()) {
        sources.push({ ...source, range: (await rangeOf(source, engineRangeOf)) ?? null });
    }
    for (const s of sources) console.log(`${s.ref.padEnd(52)} ${s.range ?? '(declares none)'}`);

    const releases = JSON.parse(await getText('https://nodejs.org/dist/index.json'));
    const choice = chooseNode(sources.map((s) => ({ id: s.id, range: s.range ?? undefined })), releases);
    if (!choice.ok) {
        console.error('\nNo Node fits every component. These ranges block:');
        for (const line of choice.blocking) console.error(`  ${line}`);
        console.error("Fix the range in the component's own package.json (engines.node), then re-run.");
        process.exit(1);
    }

    const answer = {
        $comment: "Generated by `npm run node:resolve` from each component's own engines.node. Do not edit.",
        node: choice.major,
        sources,
        excluded: excludedNodeSources(),
    };
    console.log(`\nDemo Builder runs on Node ${answer.node}`);

    if (CHECK) {
        if (!sameAnswer(readCurrent(), answer)) {
            console.error(`\n${OUT} is out of date. Run: npm run node:resolve`);
            process.exit(1);
        }
        console.log(`${OUT} is up to date.`);
        return;
    }
    writeFileSync(OUT, `${JSON.stringify(answer, null, 4)}\n`);
    console.log(`Wrote ${OUT}`);
}

main().catch((error) => {
    console.error(error.message);
    process.exit(1);
});
