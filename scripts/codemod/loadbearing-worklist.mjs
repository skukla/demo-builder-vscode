#!/usr/bin/env node
/**
 * Produce the definitive list of LOAD-BEARING casts: every place where removing a
 * cast makes the compiler object, with its reason.
 *
 *   node scripts/codemod/loadbearing-worklist.mjs > reports/loadbearing-casts.md
 *
 * WHY THIS IS THE ARTIFACT THAT MATTERS. The mechanical work is finished: every
 * syntactic position has been swept, and each remaining cast is one the compiler
 * refuses to give up. That is not a leftover pile — it is a SORTED one. A cast that
 * resists removal marks a place where the test and the code genuinely disagree, and
 * four production defects in this repo lived in exactly that gap: a field the callee
 * dispatches on, wrong or absent, with twelve tests agreeing.
 *
 * Reading 1,275 casts is not a plan. Reading a ranked list of files, each with the
 * compiler's own explanation of what breaks, is.
 *
 * HOW IT WORKS, and why it does not corrupt anything: strip every `as any` and
 * `as never` in memory, ask the compiler once, record what it says, and never save.
 * `saveTouched` is not called at all — the project is discarded. Git is untouched.
 *
 * @see .rptc/backlog/2026-09-01-cast-and-builder-worklog.md
 * @see docs/development/toolchain.md
 */
import { execFileSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { SyntaxKind } from 'ts-morph';
import { addFiles, createProject } from './project.mjs';

const project = createProject();
const files = addFiles(project, ['tests/**/*.ts', 'tests/**/*.tsx']);

// Strip in memory, then write to a THROWAWAY copy so the real tree is never touched.
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'loadbearing-'));
let stripped = 0;
const changed = [];

for (const file of files) {
    const casts = file
        .getDescendantsOfKind(SyntaxKind.AsExpression)
        .filter((c) => ['any', 'never'].includes(c.getTypeNode()?.getText()))
        .reverse();
    if (casts.length === 0) continue;
    for (const cast of casts) {
        cast.replaceWithText(cast.getExpression().getText());
        stripped += 1;
    }
    changed.push(path.relative(process.cwd(), file.getFilePath()));
}

console.error(`stripped ${stripped} cast(s) across ${changed.length} file(s), in memory`);
console.error('backing up, applying, asking the compiler once, then restoring...');

// Back up exactly what will be written, so restoration cannot depend on git state.
for (const rel of changed) {
    const dest = path.join(scratch, rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(rel, dest);
}

let blob = '';
try {
    for (const file of project.getSourceFiles()) {
        const rel = path.relative(process.cwd(), file.getFilePath());
        if (changed.includes(rel)) fs.writeFileSync(rel, file.getFullText());
    }
    try {
        blob = execFileSync('npm', ['run', 'typecheck:tests'], { encoding: 'utf8' });
    } catch (e) {
        blob = `${e.stdout ?? ''}${e.stderr ?? ''}`;
    }
} finally {
    // ALWAYS restore, even if the compiler run throws.
    for (const rel of changed) fs.copyFileSync(path.join(scratch, rel), rel);
    fs.rmSync(scratch, { recursive: true, force: true });
    console.error('restored.');
}

const rows = [...blob.matchAll(/^(tests\/[^(]+)\((\d+),\d+\): error TS\d+: (.+)$/gm)];
const byFile = new Map();
for (const [, f, line, msg] of rows) {
    if (!byFile.has(f)) byFile.set(f, []);
    byFile.get(f).push({ line, msg: msg.slice(0, 150) });
}

const ranked = [...byFile].sort((a, b) => b[1].length - a[1].length);

/**
 * `--json` dumps EVERY row instead of the markdown.
 *
 * The report deliberately elides repeats within a file — the same message on ten
 * lines is one finding to a reader. That makes it the wrong input for a sweep
 * organised by TYPE rather than by file, which needs every site. Same single
 * compiler run either way; only the rendering differs.
 */
if (process.argv.includes('--json')) {
    console.log(
        JSON.stringify(
            rows.map(([, f, line, msg]) => ({ file: f, line: Number(line), msg })),
            null,
            2
        )
    );
    process.exit(0);
}

console.log('# Load-bearing casts — where a test disagrees with the code\n');
// A stale report reads exactly like a fresh one — that cost a wrong "the worklist is
// current" on 2026-09-01, because this script prints to STDOUT and the caller has to
// redirect it (see the usage line above). The stamp makes staleness visible.
console.log(`_Generated ${new Date().toISOString()} — regenerate before trusting these counts._\n`);
console.log('Generated by `scripts/codemod/loadbearing-worklist.mjs`. Reads only.\n');
console.log(
    `Removing all ${stripped} \`as any\`/\`as never\` casts makes the compiler raise ` +
        `**${rows.length} errors across ${byFile.size} files**. Each is a place where a cast ` +
        `is holding back a real type error.\n`
);
console.log('Ranked by error count. Start at the top.\n');

for (const [f, errs] of ranked) {
    console.log(`## ${f}  (${errs.length})\n`);
    const seen = new Set();
    for (const e of errs) {
        const key = e.msg.slice(0, 60);
        if (seen.has(key)) continue;
        seen.add(key);
        console.log(`- line ${e.line}: ${e.msg}`);
    }
    console.log();
}
