/**
 * The Demo Inspector loader — pure text, no I/O.
 *
 * Inspector Tagging (`inspectorHelpers.ts`) vendors the SDK and writes
 * `scripts/demo-inspector-init.js`; something on the page then has to import it and call
 * `initInspector()` once the page's blocks are decorated. Until 2026-10-29 that was a
 * snippet appended to `scripts/delayed.js`, which Adobe's own `loadDelayed()` imported 3 s
 * after every section had loaded. Adobe's B2B template removed `delayed.js` on 2026-07-30
 * (boilerplate-b2b-template d966eff9e), and its delayed loading now waits for cookie consent,
 * which its placeholder declines by default — so on a B2B storefront the Inspector never
 * loaded. The loader now sits in `head.html`, in a Demo Builder marked block beside the
 * eager 404 script, and does that waiting itself.
 *
 * `storefrontCodeBlocks.ts` writes it; `INSPECTOR_DELAYED_SNIPPET` is the old text it takes
 * out of `delayed.js` once the loader is in place, so the Inspector never starts twice.
 */

export const INSPECTOR_LOADER_MARKER_START = '<!-- === Demo Inspector loader (Demo Builder) === -->';
export const INSPECTOR_LOADER_MARKER_END = '<!-- === end Demo Inspector loader === -->';

/**
 * The loader block for `head.html`. `__NONCE__` becomes the page's CSP nonce.
 *
 * Waits for the `load` event, then until every `main .section` reads
 * `data-section-status="loaded"` (Adobe's `aem.js` sets it, in both templates), then 3 s
 * more — Adobe's old `loadDelayed()` delay. Gives up waiting for sections after 15 s and
 * loads anyway, so a section that never finishes cannot keep the Inspector off the page.
 * The init script is read under the storefront's code base path (`window.hlx.codeBasePath`,
 * set by `aem.js`), and a missing one is swallowed.
 */
export const INSPECTOR_LOADER_TEMPLATE = `

${INSPECTOR_LOADER_MARKER_START}
<script nonce="__NONCE__" type="module">
  // Loads the Demo Inspector's tagging late in the page load, when
  // scripts/delayed.js used to run: 3 s after every section of the page has
  // loaded. Adobe's B2B template has no delayed.js, and its delayed loading
  // waits for cookie consent; this does not.
  const AFTER_SECTIONS_MS = 3000;
  const POLL_MS = 250;
  const GIVE_UP_MS = 15000;
  const sectionsLoaded = () => !document.querySelector('main .section:not([data-section-status="loaded"])');
  async function loadInspector() {
    try {
      const base = (window.hlx && window.hlx.codeBasePath) || '';
      const { initInspector } = await import(\`\${base}/scripts/demo-inspector-init.js\`);
      initInspector();
    } catch (_) { /* Inspector not available */ }
  }
  function whenSectionsLoaded(started) {
    if (sectionsLoaded() || Date.now() - started > GIVE_UP_MS) {
      setTimeout(loadInspector, AFTER_SECTIONS_MS);
    } else {
      setTimeout(() => whenSectionsLoaded(started), POLL_MS);
    }
  }
  const start = () => whenSectionsLoaded(Date.now());
  if (document.readyState === 'complete') start();
  else window.addEventListener('load', start, { once: true });
</script>
${INSPECTOR_LOADER_MARKER_END}
`;

/**
 * The loader Demo Builder appended to `scripts/delayed.js` before 2026-10-29, verbatim. It
 * is taken out only where it appears exactly like this: a copy someone edited by hand is
 * theirs, and is left (and logged).
 */
export const INSPECTOR_DELAYED_SNIPPET = `
// Demo Inspector (auto-generated by Demo Builder)
try {
  const { initInspector } = await import('./demo-inspector-init.js');
  initInspector();
} catch { /* Inspector not available */ }
`;

/** Text that shows the old loader is in `delayed.js`, edited or not. */
export const INSPECTOR_DELAYED_MARKER = 'demo-inspector-init';
